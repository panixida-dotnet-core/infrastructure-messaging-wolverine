using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

using PANiXiDA.Core.Infrastructure.Messaging.Wolverine.Generators.Validation;

namespace PANiXiDA.Core.Infrastructure.Messaging.Wolverine.Generators.Options;

/// <summary>
/// Generates reflection-free configuration binders for Wolverine options and their derived types.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class OptionBindingGenerator : IIncrementalGenerator
{
    private const string OptionsNamespace = "PANiXiDA.Core.Infrastructure.Messaging.Wolverine.Options.";
    private const string Registry = "global::PANiXiDA.Core.Infrastructure.Messaging.Wolverine.Generation.OptionBindingRegistry";

    private static readonly DiagnosticDescriptor UnsupportedOption = new(
        "PANWOLVSG002", "Options cannot be bound by the source generator",
        "Options '{0}' cannot be bound without reflection: {1}", "OptionBinding",
        DiagnosticSeverity.Error, isEnabledByDefault: true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, Generate);
    }

    private static void Generate(SourceProductionContext context, Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName(Registry.Substring("global::".Length)) is null)
        {
            return;
        }

        var optionTypes = new[] { "KafkaBrokerOption", "KafkaProducerOption", "KafkaConsumerOption", "RecurringCommandOption" }
            .Select(name => compilation.GetTypeByMetadataName(OptionsNamespace + name))
            .Where(type => type is not null).ToArray();
        var source = new StringBuilder("""
            // <auto-generated />
            #nullable enable
            #pragma warning disable CA2255, CS0618

            file static class GeneratedWolverineOptionBindings
            {
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                internal static void Initialize()
                {

            """);
        var seen = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
        foreach (var type in GetCandidates(compilation, context.CancellationToken)
                     .Where(type => IsOption(type, optionTypes))
                     .OrderBy(type => type.ToDisplayString(), StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            if (!seen.Add(type))
            {
                continue;
            }

            if (!compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            {
                if (SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, compilation.Assembly))
                {
                    context.ReportDiagnostic(Diagnostic.Create(UnsupportedOption, type.Locations.FirstOrDefault(),
                        type.Name, "the type must be accessible to generated code"));
                }

                continue;
            }

            var binding = BuildBinding(type, out var error);
            if (error is not null)
            {
                context.ReportDiagnostic(Diagnostic.Create(UnsupportedOption,
                    type.Locations.FirstOrDefault(location => location.IsInSource), type.Name, error));
                continue;
            }

            source.Append(binding);
        }

        source.Append("    }\n}\n");
        context.AddSource("OptionBindings.g.cs", source.ToString());
    }

    private static IEnumerable<INamedTypeSymbol> GetCandidates(Compilation compilation, CancellationToken token)
    {
        var declaredTypes = compilation.SourceModule.ReferencedAssemblySymbols.Append(compilation.Assembly)
            .SelectMany(assembly => ValidatorRegistrationGenerator.EnumerateTypes(assembly.GlobalNamespace))
            .Where(type => !type.IsAbstract && !ValidatorRegistrationGenerator.HasTypeParameters(type));
        return declaredTypes.Concat(GetClosedTypes(compilation, token));
    }

    private static IEnumerable<INamedTypeSymbol> GetClosedTypes(Compilation compilation, CancellationToken token)
    {
        // Closed generic options may appear only at a registration call site.
        foreach (var tree in compilation.SyntaxTrees)
        {
            var model = compilation.GetSemanticModel(tree);
            var methods = tree.GetRoot(token).DescendantNodes().OfType<GenericNameSyntax>()
                .Select(name => model.GetSymbolInfo(name, token).Symbol).OfType<IMethodSymbol>();
            foreach (var type in methods.SelectMany(method => method.TypeArguments).OfType<INamedTypeSymbol>()
                         .Where(type => !type.IsAbstract && !ContainsTypeParameter(type)))
            {
                yield return type;
            }
        }
    }

    private static bool ContainsTypeParameter(INamedTypeSymbol type)
    {
        return type.TypeArguments.Any(argument => argument is ITypeParameterSymbol ||
            argument is INamedTypeSymbol named && ContainsTypeParameter(named));
    }

    private static bool IsOption(INamedTypeSymbol type, INamedTypeSymbol?[] optionTypes)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (optionTypes.Any(option => SymbolEqualityComparer.Default.Equals(current, option)))
            {
                return true;
            }
        }

        return false;
    }

    private static string BuildBinding(INamedTypeSymbol type, out string? error)
    {
        error = null;
        if (!type.InstanceConstructors.Any(constructor => constructor.Parameters.Length == 0 &&
                constructor.DeclaredAccessibility == Accessibility.Public))
        {
            error = "a public parameterless constructor is required";
            return string.Empty;
        }

        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var source = new StringBuilder().Append("        ").Append(Registry).Append(".Register<")
            .Append(typeName).Append(">(static section =>\n        {\n            var option = new ")
            .Append(typeName).Append("();\n")
            .Append("            var children = new global::System.Collections.Generic.Dictionary<string, global::Microsoft.Extensions.Configuration.IConfigurationSection>(global::System.StringComparer.OrdinalIgnoreCase);\n")
            .Append("            foreach (var child in section.GetChildren())\n            {\n                children[child.Key] = child;\n            }\n");
        var propertyIndex = 0;
        foreach (var property in GetProperties(type))
        {
            var conversion = GetConversion(property.Type);
            if (conversion is null || property.SetMethod!.IsInitOnly)
            {
                error = $"property '{property.Name}' must have a public setter and a supported scalar type";
                return string.Empty;
            }

            AppendProperty(source, property, conversion, propertyIndex++);
        }

        return source.Append("            return option;\n        });\n").ToString();
    }

    private static IEnumerable<IPropertySymbol> GetProperties(INamedTypeSymbol type)
    {
        var names = new HashSet<string>(StringComparer.Ordinal);
        for (var current = type; current is not null; current = current.BaseType)
        {
            foreach (var property in current.GetMembers().OfType<IPropertySymbol>())
            {
                if (names.Add(property.Name) && !property.IsStatic && !property.IsIndexer &&
                    property.GetMethod?.DeclaredAccessibility == Accessibility.Public &&
                    property.SetMethod?.DeclaredAccessibility == Accessibility.Public)
                {
                    yield return property;
                }
            }
        }
    }

    private static void AppendProperty(StringBuilder source, IPropertySymbol property, string conversion, int index)
    {
        var key = property.GetAttributes().FirstOrDefault(attribute =>
            attribute.AttributeClass?.ToDisplayString() == "Microsoft.Extensions.Configuration.ConfigurationKeyNameAttribute")
            ?.ConstructorArguments.FirstOrDefault().Value as string ?? property.Name;
        var child = "child" + index;
        source.Append("            if (children.TryGetValue(")
            .Append(SymbolDisplay.FormatLiteral(key, true)).Append(", out var ").Append(child).Append("))\n            {\n")
            .Append("                option.@").Append(property.Name).Append(" = ");
        if (property.Type.SpecialType == SpecialType.System_String)
        {
            source.Append(child).Append(".Value!;\n");
        }
        else
        {
            var nullable = property.Type is INamedTypeSymbol named && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
            source.Append(nullable ? "global::System.String.IsNullOrEmpty(" + child + ".Value)" : child + ".Value is null")
                .Append(" ? default(").Append(property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .Append(") : ").Append(Registry)
                .Append(".Parse(").Append(child).Append(", static value => ").Append(conversion).Append(");\n");
        }

        source.Append("            }\n");
    }

    private static string? GetConversion(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol named && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            type = named.TypeArguments[0];
        }

        type = type.WithNullableAnnotation(NullableAnnotation.NotAnnotated);

        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        if (type.TypeKind == TypeKind.Enum)
        {
            return $"global::System.Enum.Parse<{typeName}>(value, ignoreCase: true)";
        }

        if (type.ToDisplayString() == "System.Uri")
        {
            return $"({typeName})new global::System.UriTypeConverter().ConvertFromInvariantString(value)!";
        }

        var converter = type.SpecialType switch
        {
            SpecialType.System_String => "StringConverter",
            SpecialType.System_Boolean => "BooleanConverter",
            SpecialType.System_Char => "CharConverter",
            SpecialType.System_Byte => "ByteConverter",
            SpecialType.System_SByte => "SByteConverter",
            SpecialType.System_Int16 => "Int16Converter",
            SpecialType.System_UInt16 => "UInt16Converter",
            SpecialType.System_Int32 => "Int32Converter",
            SpecialType.System_UInt32 => "UInt32Converter",
            SpecialType.System_Int64 => "Int64Converter",
            SpecialType.System_UInt64 => "UInt64Converter",
            SpecialType.System_Single => "SingleConverter",
            SpecialType.System_Double => "DoubleConverter",
            SpecialType.System_Decimal => "DecimalConverter",
            SpecialType.System_DateTime => "DateTimeConverter",
            _ => type.ToDisplayString() switch
            {
                "System.Guid" => "GuidConverter",
                "System.TimeSpan" => "TimeSpanConverter",
                "System.DateTimeOffset" => "DateTimeOffsetConverter",
                "System.DateOnly" => "DateOnlyConverter",
                "System.TimeOnly" => "TimeOnlyConverter",
                _ => null,
            },
        };
        return converter is null ? null : $"({typeName})new global::System.ComponentModel.{converter}().ConvertFromInvariantString(value)!";
    }
}
